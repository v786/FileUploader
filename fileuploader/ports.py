"""Ports. Workers and API code depend only on these; adapters are picked from
config (VENDOR_MODE=mock|live), so swapping in real vendors is configuration only."""
from __future__ import annotations

from typing import Protocol


class ObjectStore(Protocol):
    def create_multipart(self, key: str) -> str: ...
    def abort_multipart(self, key: str, upload_id: str) -> None: ...
    def list_parts(self, key: str, upload_id: str) -> dict[int, tuple[str, int]]: ...
    def complete_multipart(self, key: str, upload_id: str, parts: list[tuple[int, str]]) -> str: ...
    def presign_part(self, key: str, upload_id: str, part_number: int, ttl_s: int) -> str: ...
    def presign_put(self, key: str, ttl_s: int) -> str: ...
    def presign_get(self, key: str, ttl_s: int) -> str: ...
    def head(self, key: str) -> int | None: ...
    def get_range(self, key: str, start: int, end: int) -> bytes: ...
    def put(self, key: str, data: bytes) -> str: ...


class Scanner(Protocol):
    async def scan(self, *, file_id: str, key: str, name: str, idempotency_key: str) -> dict: ...


class Extractor(Protocol):
    async def extract(self, *, file_id: str, key: str, name: str, size_bytes: int, idempotency_key: str) -> dict: ...


class Thumbnailer(Protocol):
    async def thumbnail(self, *, file_id: str, key: str, name: str, idempotency_key: str) -> dict: ...


class Processor(Protocol):
    """External processing API, async job model: submit returns a job id; completion
    arrives by webhook, with status polls as the fallback."""
    async def submit(self, *, file_id: str, name: str, source_url: str, idempotency_key: str) -> dict: ...
    async def status(self, *, job_id: str) -> dict: ...
